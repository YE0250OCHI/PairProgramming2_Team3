-- DB作成
CREATE DATABASE TaxiManagementDb;
GO

-- DB接続
USE TaxiManagementDb;
GO



-- JOB状態テーブル
CREATE TABLE job_status (
	id INT PRIMARY KEY IDENTITY(1,1),
	status_name NVARCHAR(10) NOT NULL UNIQUE
);
GO

-- タクシー状態テーブル
CREATE TABLE taxi_status (
	id INT PRIMARY KEY IDENTITY(1,1),
	status_name NVARCHAR(10) NOT NULL UNIQUE
);
GO

-- タクシーテーブル
CREATE TABLE taxis(
	id CHAR(5) PRIMARY KEY,
	taxi_status_id INT NOT NULL,
	driver_name NVARCHAR(20) NOT NULL,

	FOREIGN KEY(taxi_status_id) REFERENCES taxi_status(id)
);
GO

-- JOBテーブル
CREATE TABLE jobs (
	id CHAR(14) PRIMARY KEY,
	job_status_id INT NOT NULL,
	taxi_id CHAR(5),
	from_loc NVARCHAR(20) NOT NULL,
	to_loc NVARCHAR(20) NOT NULL,
	created_at DATETIME NOT NULL DEFAULT GETDATE(),
	closed_at DATETIME NULL,
	
	FOREIGN KEY(job_status_id) REFERENCES job_status(id),	
	FOREIGN KEY(taxi_id) REFERENCES taxis(id)
);
GO



